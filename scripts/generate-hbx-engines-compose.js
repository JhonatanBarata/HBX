#!/usr/bin/env node

const fs = require("fs");
const path = require("path");

const DEFAULT_TOTAL_COUNT = 100;
const DEFAULT_ACTIVE_COUNT = 50;
const HARD_LIMIT = 100;
const outputFile = path.resolve(process.cwd(), "docker-compose.hbx-engines.generated.yml");

function getArgValue(name, position) {
  const prefix = `--${name}=`;
  const named = process.argv.slice(2).find((arg) => String(arg || "").startsWith(prefix));
  if (named) return named.slice(prefix.length);
  return process.argv[position + 2];
}

function parseCount(value, fallback) {
  const raw = String(value || "").trim();
  if (!raw) return fallback;
  const parsed = Number(raw);
  if (!Number.isFinite(parsed)) return fallback;
  return Math.min(Math.max(Math.trunc(parsed), 1), HARD_LIMIT);
}

const totalCount = parseCount(
  process.env.HBX_ENGINE_TOTAL_COUNT || process.env.HBX_ENGINE_MAX_COUNT || getArgValue("total", 0),
  DEFAULT_TOTAL_COUNT,
);
const activeCount = Math.min(
  parseCount(
    process.env.HBX_ENGINE_ACTIVE_COUNT || process.env.HBX_ENGINE_COUNT || getArgValue("active", 1),
    DEFAULT_ACTIVE_COUNT,
  ),
  totalCount,
);
const urls = Array.from({ length: activeCount }, (_, index) => `http://hbx-engine-${index + 1}:8001`);
const shellEngineCount = '$${HBX_ENGINE_COUNT:-' + activeCount + '}';
const shellWatchdogInterval = '$${HBX_WATCHDOG_INTERVAL_SECONDS:-45}';
const dependsOn = Array.from({ length: activeCount }, (_, index) => `      - hbx-engine-${index + 1}`).join("\n");
const services = Array.from({ length: totalCount }, (_, index) => {
  const n = index + 1;
  const profiles = n > activeCount ? `    profiles:\n      - future-engines\n` : "";
  return `  hbx-engine-${n}:
    <<: *hbx-engine-common
    container_name: hbx-engine-${n}
${profiles}    volumes:
      - data-${n}:/app/data
`;
}).join("\n");
const volumes = Array.from({ length: totalCount }, (_, index) => `  data-${index + 1}:`).join("\n");

const compose = `# Generated by scripts/generate-hbx-engines-compose.js
# Motores hbx-engine-1..hbx-engine-${activeCount} ativos por padrao.
# Motores hbx-engine-${activeCount + 1}..hbx-engine-${totalCount} reservados para crescimento futuro via profile future-engines.
# Para ativar ${totalCount} no futuro, remova o profile future-engines dos motores reservados ou gere com active=${totalCount}.
# Usage: node scripts/generate-hbx-engines-compose.js --total=${totalCount} --active=${activeCount}

x-hbx-engine-common: &hbx-engine-common
  build:
    context: ./hbx-scraping-engine
    dockerfile: Dockerfile
  restart: unless-stopped
  environment:
    HBX_SCRAPING_USER_AGENT: \${HBX_SCRAPING_USER_AGENT:-HBX-Scraping/0.1 contato@hbxsystem.com.br}
    HBX_SCRAPING_TIMEOUT_SECONDS: \${HBX_SCRAPING_TIMEOUT_SECONDS:-20}
    HBX_SCRAPING_CONCURRENCY: \${HBX_SCRAPING_CONCURRENCY:-3}
    HBX_SCRAPING_CACHE_TTL_HOURS: \${HBX_SCRAPING_CACHE_TTL_HOURS:-24}
    HBX_SCRAPING_MAX_DISCOVERY_RESULTS: \${HBX_SCRAPING_MAX_DISCOVERY_RESULTS:-120}
    HBX_AGENDA_MAX_PAGES: \${HBX_AGENDA_MAX_PAGES:-20}
    HBX_AGENDA_REQUEST_DELAY_MS: \${HBX_AGENDA_REQUEST_DELAY_MS:-700}
  networks:
    - hbx_net
services:
  backend:
    environment:
      HBX_ENGINE_COUNT: "${activeCount}"
      HBX_ENGINE_MAX_COUNT: "${totalCount}"
      HBX_ENGINE_URLS: "${urls.join(",")}"
    depends_on:
${dependsOn}

${services}
  hbx-engine-watchdog:
    image: docker:27-cli
    container_name: hbx-engine-watchdog
    restart: unless-stopped
    environment:
      HBX_ENGINE_COUNT: "${activeCount}"
      HBX_WATCHDOG_INTERVAL_SECONDS: \${HBX_WATCHDOG_INTERVAL_SECONDS:-45}
    volumes:
      - /var/run/docker.sock:/var/run/docker.sock
    networks:
      - hbx_net
    command: >
      sh -c '
        while true; do
          for i in $$(seq 1 ${shellEngineCount}); do
            name="hbx-engine-$$i";
            status="$$(docker inspect -f "{{.State.Status}}" "$$name" 2>/dev/null || true)";
            health="$$(docker inspect -f "{{if .State.Health}}{{.State.Health.Status}}{{else}}no-health{{end}}" "$$name" 2>/dev/null || true)";
            if [ "$$status" != "running" ]; then
              echo "[hbx-watchdog] starting $$name status=$$status";
              docker start "$$name" >/dev/null 2>&1 || true;
            elif [ "$$health" = "unhealthy" ]; then
              echo "[hbx-watchdog] restarting $$name health=$$health";
              docker restart "$$name" >/dev/null 2>&1 || true;
            fi;
          done;
          sleep ${shellWatchdogInterval};
        done
      '
    depends_on:
${dependsOn}

volumes:
${volumes}

networks:
  hbx_net:
    name: \${HBX_DOCKER_NETWORK:-hbx_net}
    external: true
`;

fs.writeFileSync(outputFile, compose, "utf8");
console.log(`Generated ${path.relative(process.cwd(), outputFile)} with ${activeCount}/${totalCount} active HBX engines.`);

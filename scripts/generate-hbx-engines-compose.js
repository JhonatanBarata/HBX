#!/usr/bin/env node

const fs = require("fs");
const path = require("path");

const DEFAULT_COUNT = 20;
const DEFAULT_HARD_LIMIT = 200;
const outputFile = path.resolve(process.cwd(), "docker-compose.hbx-engines.generated.yml");

function parseCount(value, fallback, min, max) {
  const raw = String(value || "").trim();
  if (!raw) return fallback;
  const parsed = Number(raw);
  if (!Number.isFinite(parsed)) return fallback;
  return Math.min(Math.max(Math.trunc(parsed), min), max);
}

const hardLimit = parseCount(process.env.HBX_ENGINE_HARD_LIMIT || process.env.HBX_ENGINE_MAX_COUNT, DEFAULT_HARD_LIMIT, 1, DEFAULT_HARD_LIMIT);
const defaultCount = parseCount(process.env.HBX_ENGINE_DEFAULT_COUNT, DEFAULT_COUNT, 1, hardLimit);
const count = parseCount(process.env.HBX_ENGINE_COUNT || process.argv[2], defaultCount, 1, hardLimit);
const urls = Array.from({ length: count }, (_, index) => `http://hbx-engine-${index + 1}:8001`);
const services = Array.from({ length: count }, (_, index) => {
  const n = index + 1;
  return `  hbx-engine-${n}:
    <<: *hbx-engine-common
    container_name: hbx-engine-${n}
    volumes:
      - data-${n}:/app/data
`;
}).join("\n");
const volumes = Array.from({ length: count }, (_, index) => `  data-${index + 1}:`).join("\n");

const compose = `# Generated by scripts/generate-hbx-engines-compose.js
# Capacidade declarada atual: hbx-engine-1..hbx-engine-${count}.
# HBX_ENGINE_COUNT define a capacidade declarada; Governor decide quantos ficam vivos.
# Hard limit aplicado pelo gerador: ${hardLimit}.
# Usage: HBX_ENGINE_COUNT=${count} node scripts/generate-hbx-engines-compose.js

x-hbx-engine-common: &hbx-engine-common
  build:
    context: ./hbx-scraping-engine
    dockerfile: Dockerfile
  restart: unless-stopped
  environment:
    HBX_SCRAPING_USER_AGENT: \${HBX_SCRAPING_USER_AGENT:-HBX-Scraping/0.1 contato@hbxsystem.com.br}
    HBX_SCRAPING_TIMEOUT_SECONDS: \${HBX_SCRAPING_TIMEOUT_SECONDS:-20}
    HBX_SCRAPING_CONCURRENCY: \${HBX_SCRAPING_CONCURRENCY:-3}
    HBX_SCRAPING_CACHE_TTL_HOURS: \${HBX_SCRAPING_CACHE_TTL_HOURS:-24}
    HBX_SCRAPING_MAX_DISCOVERY_RESULTS: \${HBX_SCRAPING_MAX_DISCOVERY_RESULTS:-120}
    HBX_AGENDA_MAX_PAGES: \${HBX_AGENDA_MAX_PAGES:-20}
    HBX_AGENDA_REQUEST_DELAY_MS: \${HBX_AGENDA_REQUEST_DELAY_MS:-700}
  networks:
    - hbx_net
services:
  backend:
    environment:
      HBX_ENGINE_COUNT: "${count}"
      HBX_ENGINE_MAX_COUNT: "${count}"
      HBX_ENGINE_URLS: "${urls.join(",")}"

${services}

volumes:
${volumes}

networks:
  hbx_net:
    name: \${HBX_DOCKER_NETWORK:-hbx_net}
    external: true
`;

fs.writeFileSync(outputFile, compose, "utf8");
console.log(`Generated ${path.relative(process.cwd(), outputFile)} with ${count} HBX engines.`);
